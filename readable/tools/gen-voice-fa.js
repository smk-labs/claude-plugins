#!/usr/bin/env node
'use strict';
/**
 * Writes hooks/voice-fa.md from daily-tools/skills/gouya/SKILL.md.
 *
 *   node readable/tools/gen-voice-fa.js           rewrite the file
 *   node readable/tools/gen-voice-fa.js --check   exit 1 if it is out of date
 *
 * The Persian voice and the gouya skill are the same document with two
 * delivery paths: readable names the voice file at SessionStart so every
 * Persian reply is worded by it, and daily-tools ships the skill so it can be
 * invoked over a file the user hands it. Both were hand-maintained for one
 * release, which is exactly the second copy CLAUDE.md forbids: the two carried
 * different names for the same rules within a day of each other.
 *
 * The skill is the source because it is the one a person edits. readable
 * derives, and ships the derived file, so the plugin stays standalone: a
 * machine that installs readable alone still gets the voice, with no runtime
 * dependency on daily-tools being installed too.
 *
 * test.js runs --check, so the copy cannot be stale for longer than one test
 * run.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SOURCE = path.join(ROOT, 'daily-tools', 'skills', 'gouya', 'SKILL.md');
const TARGET = path.join(__dirname, '..', 'hooks', 'voice-fa.md');

const NOTE = '<!-- GENERATED by readable/tools/gen-voice-fa.js from ' +
  'daily-tools/skills/gouya/SKILL.md — do not edit, edit the skill and regenerate ' +
  '(test.js fails on drift). -->';

function build() {
  const src = fs.readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n');
  const end = src.indexOf('\n---\n', 4);
  if (!src.startsWith('---\n') || end === -1) {
    throw new Error('gouya SKILL.md has no frontmatter to carry over');
  }
  /* The note sits AFTER the frontmatter, not above it: a comment on line 1
   * turns the block into body text for anything that parses the front of the
   * file, and the skill loader is one such thing. */
  const head = src.slice(0, end + 5);
  const body = src.slice(end + 5).replace(/^\n+/, '');
  return head + '\n' + NOTE + '\n\n' + body.replace(/\s*$/, '') + '\n';
}

const text = build();

if (process.argv.indexOf('--check') !== -1) {
  let have = '';
  try { have = fs.readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n'); } catch (e) { have = ''; }
  if (have !== text) {
    process.stderr.write('stale, run `node readable/tools/gen-voice-fa.js`:\n  ' +
      path.relative(ROOT, TARGET) + '\n');
    process.exit(1);
  }
  process.stdout.write('voice-fa.md is up to date\n');
  process.exit(0);
}

fs.writeFileSync(TARGET, text);
process.stdout.write('wrote ' + path.relative(ROOT, TARGET) + ' (' + text.length + ' bytes)\n');
