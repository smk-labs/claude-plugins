#!/usr/bin/env node
'use strict';
/**
 * Writes hooks/voice-fa.md from the core block of daily-tools/skills/gouya/SKILL.md.
 *
 *   node readable/tools/gen-voice-fa.js           rewrite the file
 *   node readable/tools/gen-voice-fa.js --check   exit 1 if it is out of date
 *
 * The Persian voice and the gouya skill are one document with two delivery
 * paths. The skill is the source because it is the one a person edits; readable
 * ships a derived copy so it stays standalone.
 *
 * Since 7.0.0 only the `<!--@core-->` block is derived, and the SessionStart
 * hook injects it whole. Until then the hook named the full 14KB skill and the
 * model spent a turn reading it before the first Persian reply of every
 * session. The rest of the skill explains and gives examples, which is what a
 * person editing it needs and what a model writing a reply does not.
 *
 * test.js runs --check, so the copy cannot be stale for longer than one test run.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SOURCE = path.join(ROOT, 'daily-tools', 'skills', 'gouya', 'SKILL.md');
const TARGET = path.join(__dirname, '..', 'hooks', 'voice-fa.md');

const NOTE = '<!-- GENERATED by readable/tools/gen-voice-fa.js from the core block of ' +
  'daily-tools/skills/gouya/SKILL.md; edit the skill and regenerate (test.js fails on drift). -->';

function build() {
  const src = fs.readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n');
  const m = src.match(/<!--@core[^>]*-->\n([\s\S]*?)\n<!--@\/core-->/);
  if (!m) throw new Error('gouya SKILL.md has no <!--@core--> block to derive');
  return NOTE + '\n' + m[1].trim() + '\n';
}

const text = build();

if (process.argv.indexOf('--check') !== -1) {
  let have = '';
  try { have = fs.readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n'); } catch (e) { have = ''; }
  if (have !== text) {
    process.stderr.write('stale, run `node readable/tools/gen-voice-fa.js`:\n  ' +
      path.relative(ROOT, TARGET) + '\n');
    process.exit(1);
  }
  process.stdout.write('voice-fa.md is up to date\n');
  process.exit(0);
}

fs.writeFileSync(TARGET, text);
process.stdout.write('wrote ' + path.relative(ROOT, TARGET) + ' (' + text.length + ' bytes)\n');
